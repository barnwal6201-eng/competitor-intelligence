// Phase 10: battlecard / change -> Notion blocks. Pure functions — no
// database, no network — so they are unit-testable: give them a
// battlecard (or a change) and they return the Notion page blocks.
//
// The blocks only restate what the battlecard already holds (verified
// data from snapshots/changes, AI sections labelled as AI-generated in
// the text). Nothing is invented here. Notion's API caps a page create
// at 100 children, so every list is capped and long text is truncated
// to 2,000 characters per rich-text run (Notion's limit).

import type { IBattlecard } from "../models/Battlecard";
import type { IChange } from "../models/Change";

export interface NotionText {
  type: "text";
  text: { content: string; link?: { url: string } | null };
}

export interface NotionBlock {
  type: string;
  [key: string]: unknown;
}

const MAX_RUN = 2000;

function rich(text: string): NotionText[] {
  const clean = (text || "").replace(/\s+/g, " ").trim() || "—";
  return [{ type: "text", text: { content: clean.slice(0, MAX_RUN) } }];
}

function heading(level: 1 | 2 | 3, text: string): NotionBlock {
  return { type: `heading_${level}`, [`heading_${level}`]: { rich_text: rich(text) } };
}

function para(text: string): NotionBlock {
  return { type: "paragraph", paragraph: { rich_text: rich(text) } };
}

function bullet(text: string): NotionBlock {
  return { type: "bulleted_list_item", bulleted_list_item: { rich_text: rich(text) } };
}

function section(title: string, items: string[], emptyNote: string): NotionBlock[] {
  const blocks: NotionBlock[] = [heading(2, title)];
  if (items.length === 0) {
    blocks.push(para(emptyNote));
  } else {
    for (const item of items.slice(0, 20)) blocks.push(bullet(item));
  }
  return blocks;
}

function planLine(p: IBattlecard["pricing"][number]): string {
  if (p.price === null) return `${p.name} — price not listed (${p.interval})`;
  const currency = p.currency || "$";
  return `${p.name} — ${currency}${p.price} / ${p.interval}`;
}

export function battlecardToNotionBlocks(battlecard: IBattlecard, competitorName: string): NotionBlock[] {
  const blocks: NotionBlock[] = [
    para(battlecard.overview),
    para(`Positioning: ${battlecard.positioning}`),
    para(`Battlecard version ${battlecard.version} — generated by Competitor Intelligence from real snapshots and detected changes. AI sections are labelled; verify them before a sales call.`),
    ...section(
      "Pricing",
      battlecard.pricing.map(planLine),
      "No pricing plans captured yet — scan the competitor first."
    ),
    ...section(
      "Features",
      battlecard.features.map((f) => (f.date ? `${f.title} (${f.date})` : f.title)),
      "No changelog features captured yet."
    ),
    ...section("Strengths (AI-generated)", battlecard.strengths, "No AI analysis yet — run Analyse first."),
    ...section("Weaknesses (AI-generated)", battlecard.weaknesses, "No AI analysis yet — run Analyse first."),
    ...section(
      "Recent changes",
      battlecard.recentChanges.map(
        (c) => `[${c.significance}] ${c.title} — ${new Date(c.detectedAt).toLocaleDateString()}`
      ),
      "No changes detected yet."
    ),
    ...section(
      "Customer complaints",
      battlecard.complaints.map((c) => (c.rating !== null ? `${c.text} (${c.rating}/5)` : c.text)),
      "No low-rated reviews captured."
    ),
    ...section("Talking points (AI-generated)", battlecard.talkingPoints, "No AI analysis yet — run Analyse first."),
    ...section(
      "Objection handling (AI-generated)",
      battlecard.objectionHandling,
      "No AI analysis yet — run Analyse first."
    ),
  ];

  if (battlecard.sources.length > 0) {
    blocks.push(heading(2, "Sources"));
    for (const s of battlecard.sources.slice(0, 10)) {
      blocks.push({
        type: "bulleted_list_item",
        bulleted_list_item: {
          rich_text: [
            { type: "text", text: { content: `${s.label}: ` } },
            { type: "text", text: { content: s.url, link: { url: s.url } } },
          ],
        },
      });
    }
  }

  return blocks.slice(0, 100);
}

export function battlecardToNotionTitle(battlecard: IBattlecard, competitorName: string): string {
  return `Battlecard: ${competitorName} (v${battlecard.version})`;
}

export function changeToNotionBlocks(change: IChange, competitorName: string): NotionBlock[] {
  const blocks: NotionBlock[] = [
    para(`${competitorName} — ${change.title}`),
    para(`Category: ${change.category} · Significance: ${change.significance} · Source: ${change.sourceType}`),
    para(`Detected: ${new Date(change.detectedAt).toLocaleString()}`),
  ];
  if (change.previousValue !== undefined && change.previousValue !== null) {
    blocks.push(para(`Previous: ${String(change.previousValue).slice(0, 500)}`));
  }
  if (change.newValue !== undefined && change.newValue !== null) {
    blocks.push(para(`New: ${String(change.newValue).slice(0, 500)}`));
  }
  blocks.push(para(`Source page: ${change.sourceUrl}`));
  return blocks.slice(0, 100);
}

export function changeToNotionTitle(change: IChange, competitorName: string): string {
  return `Change: ${competitorName} — ${change.title}`.slice(0, 200);
}
