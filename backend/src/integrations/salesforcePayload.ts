// Phase 10: battlecard / change -> Salesforce Task fields. Pure
// functions — no database, no network — so they are unit-testable.
//
// Why a Task: a Salesforce Task is the one standard object a rep sees
// on their own home page and activity timeline without needing an
// Account or Opportunity to attach it to. The battlecard becomes a
// completed Task ("read this before the call") whose Description holds
// the same verified sections as the battlecard itself — nothing invented,
// AI sections labelled.

import type { IBattlecard } from "../models/Battlecard";
import type { IChange } from "../models/Change";

export interface SalesforceTaskInput {
  subject: string;
  description: string;
}

function lines(items: string[]): string {
  return items.length > 0 ? items.map((i) => `• ${i}`).join("\n") : "— none —";
}

export function battlecardToSalesforceTask(
  battlecard: IBattlecard,
  competitorName: string
): SalesforceTaskInput {
  const sections: string[] = [
    battlecard.overview,
    "",
    `Positioning: ${battlecard.positioning}`,
    "",
    "PRICING",
    lines(
      battlecard.pricing.map((p) =>
        p.price === null
          ? `${p.name} — price not listed (${p.interval})`
          : `${p.name} — ${(p.currency || "$")}${p.price} / ${p.interval}`
      )
    ),
    "",
    "FEATURES",
    lines(battlecard.features.map((f) => (f.date ? `${f.title} (${f.date})` : f.title))),
    "",
    "STRENGTHS (AI-generated)",
    lines(battlecard.strengths),
    "",
    "WEAKNESSES (AI-generated)",
    lines(battlecard.weaknesses),
    "",
    "RECENT CHANGES",
    lines(
      battlecard.recentChanges.map(
        (c) => `[${c.significance}] ${c.title} — ${new Date(c.detectedAt).toLocaleDateString()}`
      )
    ),
    "",
    "CUSTOMER COMPLAINTS",
    lines(battlecard.complaints.map((c) => (c.rating !== null ? `${c.text} (${c.rating}/5)` : c.text))),
    "",
    "TALKING POINTS (AI-generated)",
    lines(battlecard.talkingPoints),
    "",
    "OBJECTION HANDLING (AI-generated)",
    lines(battlecard.objectionHandling),
    "",
    "SOURCES",
    lines(battlecard.sources.map((s) => `${s.label}: ${s.url}`)),
    "",
    `Battlecard version ${battlecard.version} — generated by Competitor Intelligence from real snapshots and detected changes. AI sections are labelled; verify them before a sales call.`,
  ];
  return {
    subject: `Battlecard: ${competitorName} (v${battlecard.version})`,
    description: sections.join("\n").slice(0, 32000),
  };
}

export function changeToSalesforceTask(change: IChange, competitorName: string): SalesforceTaskInput {
  const sections: string[] = [
    `${competitorName} — ${change.title}`,
    "",
    `Category: ${change.category}`,
    `Significance: ${change.significance}`,
    `Source: ${change.sourceType}`,
    `Detected: ${new Date(change.detectedAt).toLocaleString()}`,
  ];
  if (change.previousValue !== undefined && change.previousValue !== null) {
    sections.push(`Previous: ${String(change.previousValue).slice(0, 1000)}`);
  }
  if (change.newValue !== undefined && change.newValue !== null) {
    sections.push(`New: ${String(change.newValue).slice(0, 1000)}`);
  }
  sections.push(`Source page: ${change.sourceUrl}`);
  return {
    subject: `Competitor change: ${competitorName} — ${change.title}`.slice(0, 255),
    description: sections.join("\n").slice(0, 32000),
  };
}
